// Swagger / OpenAPI 3.0 configuration
const swaggerJSDoc = require('swagger-jsdoc');
const swaggerUi = require('swagger-ui-express');

const PORT = Number(process.env.PORT) || 3000;

const options = {
    definition: {
        openapi: '3.0.0',
        info: {
            title: 'RESTful API Documentation - Web & Database Lab 3',
            version: '1.0.0',
            description: 'Interactive API documentation auto-generated by Swagger UI '
                + 'for the Sales Management application'
        },
        servers: [
            {
                url: `http://localhost:${PORT}/api`,
                description: 'Development Local Server'
            }
        ],
        tags: [
            { name: 'Products', description: 'Product management endpoints' },
            { name: 'Categories', description: 'Category management endpoints' }
        ],
        components: {
            parameters: {
                Id: {
                    in: 'path',
                    name: 'id',
                    required: true,
                    description: 'MongoDB ObjectId of the resource',
                    schema: { type: 'string', example: '66f1a2b3c4d5e6f7a8b9c0d1' }
                }
            },
            schemas: {
                Product: {
                    type: 'object',
                    required: ['name', 'category', 'price'],
                    properties: {
                        _id: { type: 'string', description: 'Auto-generated ID from MongoDB' },
                        name: { type: 'string', example: 'Laptop Dell XPS 15' },
                        category: {
                            type: 'string',
                            enum: ['Electronics', 'Audio', 'Accessories'],
                            example: 'Electronics'
                        },
                        price: { type: 'number', example: 35000000 },
                        stock: { type: 'integer', example: 10 },
                        description: { type: 'string', example: '15-inch laptop, 32 GB RAM' },
                        createdAt: { type: 'string', format: 'date-time' },
                        updatedAt: { type: 'string', format: 'date-time' }
                    }
                },
                ProductInput: {
                    type: 'object',
                    required: ['name', 'category', 'price'],
                    properties: {
                        name: { type: 'string', example: 'Laptop Dell XPS 15' },
                        category: {
                            type: 'string',
                            enum: ['Electronics', 'Audio', 'Accessories'],
                            example: 'Electronics'
                        },
                        price: { type: 'number', minimum: 0, example: 35000000 },
                        stock: { type: 'integer', minimum: 0, example: 10 },
                        description: { type: 'string', example: '15-inch laptop, 32 GB RAM' }
                    }
                },
                Category: {
                    type: 'object',
                    required: ['name'],
                    properties: {
                        _id: { type: 'string', description: 'Auto-generated ID from MongoDB' },
                        name: { type: 'string', example: 'Home & Living' },
                        slug: { type: 'string', example: 'home-living' },
                        description: { type: 'string', example: 'Furniture and decor' },
                        createdAt: { type: 'string', format: 'date-time' },
                        updatedAt: { type: 'string', format: 'date-time' }
                    }
                },
                CategoryInput: {
                    type: 'object',
                    required: ['name'],
                    properties: {
                        name: { type: 'string', minLength: 3, example: 'Home & Living' },
                        description: { type: 'string', example: 'Furniture and decor' }
                    }
                },
                Error: {
                    type: 'object',
                    properties: {
                        success: { type: 'boolean', example: false },
                        error: { type: 'string', example: 'No product found with the given ID' }
                    }
                }
            }
        }
    },
    // Files to scan for @swagger comments (relative to the folder you run "node server.js" from)
    apis: ['./routes/*.js', './models/*.js']
};

const swaggerSpec = swaggerJSDoc(options);

const setupSwagger = (app) => {
    app.use('/api-docs', swaggerUi.serve, swaggerUi.setup(swaggerSpec));
    console.log(`Swagger UI documentation is ready at: http://localhost:${PORT}/api-docs`);
};

module.exports = setupSwagger;
module.exports.swaggerSpec = swaggerSpec;
